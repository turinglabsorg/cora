import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { test } from "node:test";
import { Boxes, runProcess } from "../src/box.js";

test("sealed firewall resists root and blocks host, peers, LAN and tailnet while public internet and owner ports work", { skip: process.env.CORA_TEST_DOCKER !== "1", timeout: 120000 }, async (t) => {
  const docker = process.env.CORA_TEST_DOCKER_BIN || "docker";
  const id = "ag_" + randomBytes(6).toString("hex");
  const sealed = new Set([id]);
  const peerName = "cora-sealed-peer-" + id;
  const boxes = new Boxes({ docker, image: process.env.CORA_TEST_BOX_IMAGE || "cora-box:latest", timezone: "UTC", access: () => ({ sshPort: 22991 }), sealed: (value) => sealed.has(value) });
  const agent = { id, name: "Isolation verification" };
  t.after(async () => {
    await runProcess(docker, ["rm", "-f", peerName]);
    await boxes.remove(id, { volume: true });
    await runProcess(docker, ["network", "rm", "cora-sealed-" + id]);
  });
  const desktop = await boxes.create(agent);
  assert.equal(desktop.outdated, false);
  const inspect = JSON.parse((await runProcess(docker, ["inspect", boxes.name(id)])).stdout)[0];
  assert.deepEqual(inspect.Mounts.map((mount) => mount.Destination).sort(), ["/home/agent", "/var/lib/cora"]);
  assert.equal(inspect.HostConfig.Privileged, false);
  assert.ok(inspect.HostConfig.CapDrop.some((cap) => cap.endsWith("NET_RAW")));
  const guard = JSON.parse((await runProcess(docker, ["inspect", boxes.networkGuard(id)])).stdout)[0];
  for (const bindings of Object.values(guard.NetworkSettings.Ports)) for (const binding of bindings || []) assert.equal(binding.HostIp, "127.0.0.1");
  assert.deepEqual(guard.Mounts, []);
  const shell = async (command) => boxes.shell(id, command, { timeoutMs: 20000 });
  assert.notEqual((await shell("sudo iptables -F OUTPUT")).code, 0, "even root cannot change the shared namespace firewall");
  assert.notEqual((await shell("sudo python3 -c 'import socket; socket.socket(socket.AF_INET,socket.SOCK_RAW,socket.IPPROTO_ICMP)'")).code, 0);
  const network = JSON.parse((await runProcess(docker, ["network", "inspect", boxes.network(id)])).stdout)[0];
  const gateway = network.IPAM.Config[0].Gateway;
  const peer = await runProcess(docker, ["run", "-d", "--name", peerName, "--network", boxes.network(id), "--entrypoint", "python3", boxes.image, "-m", "http.server", "8971", "--bind", "0.0.0.0"]);
  assert.equal(peer.code, 0, peer.stderr);
  const live = await runProcess(docker, ["exec", peerName, "python3", "-c", "import socket; socket.create_connection(('127.0.0.1',8971),5).close()"]);
  assert.equal(live.code, 0, "the peer is actually listening before testing isolation");
  const peerInfo = JSON.parse((await runProcess(docker, ["inspect", peerName])).stdout)[0];
  const peerIp = peerInfo.NetworkSettings.Networks[boxes.network(id)].IPAddress;
  const peerProbe = await runProcess(docker, boxes.execArgs(id, ["python3", "-c", `import socket; socket.create_connection(('${peerIp}',8971),1).close()`]));
  assert.notEqual(peerProbe.code, 0, "a known live peer is unreachable");
  const probe = `import socket,sys\nfor host in ${JSON.stringify([gateway, "10.0.0.1", "192.168.1.1", "100.124.92.120", "169.254.169.254", "host.docker.internal"])}:\n try:\n  s=socket.create_connection((host,22),0.5);s.close();sys.exit('private destination reachable: '+host)\n except OSError: pass\nprint('all private destinations refused')`;
  const blocked = await runProcess(docker, boxes.execArgs(id, ["python3", "-c", probe]), { timeoutMs: 10000 });
  assert.equal(blocked.code, 0, blocked.stderr);
  const publicInternet = await shell("curl --fail --silent --show-error --connect-timeout 8 https://example.com -o /dev/null");
  assert.equal(publicInternet.code, 0, publicInternet.output);
  assert.equal((await shell("mkdir -p ~/work; echo retained > ~/work/isolation-fixture.txt")).code, 0);
  assert.equal((await fetch(`http://127.0.0.1:${desktop.port}/`)).status, 200, "the owner still reaches the desktop through its loopback port");
  await boxes.restart(id);
  assert.equal((await boxes.shell(id, "python3 -c 'import socket; socket.create_connection((\"" + gateway + "\",22),0.5)'", { timeoutMs: 5000 })).code !== 0, true, "desktop restart does not open the host route");
  sealed.delete(id);
  const reopened = await boxes.upgrade(agent);
  assert.equal(reopened.outdated, false, "unsealing replaces the namespace and releases its SSH port");
  assert.equal((await runProcess(docker, ["inspect", boxes.networkGuard(id)])).code !== 0, true);
  assert.match((await shell("cat ~/work/isolation-fixture.txt")).output, /retained/);
  assert.equal((await runProcess(docker, ["network", "connect", boxes.network(id), peerName])).code, 0);
  const normalPeer = JSON.parse((await runProcess(docker, ["inspect", peerName])).stdout)[0].NetworkSettings.Networks[boxes.network(id)].IPAddress;
  const normalProbe = await runProcess(docker, boxes.execArgs(id, ["python3", "-c", `import socket; socket.create_connection(('${normalPeer}',8971),1).close()`]));
  assert.notEqual(normalProbe.code, 0, "ordinary desktops also cannot reach another desktop's listening service");
});
